def _norm(name: str) -> str:
    text = name.strip().casefold()
    text = text.replace("\u2019", "'").replace("\u2018", "'").replace("`", "'")
    return " ".join(text.split())


_FLOOR_BY_NORM = {_norm(name): price for name, price in GIFT_FLOOR_TON.items()}


def gift_floor_ton(title: str | None) -> float | None:
    if not title:
        return None
    return _FLOOR_BY_NORM.get(_norm(title))
